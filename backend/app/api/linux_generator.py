"""Offline Debian/Ubuntu configuration artifact generator; never executes commands remotely."""
import ipaddress
import json
import re
from typing import Literal

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app.database.models import User
from app.security.dependencies import get_current_user

router = APIRouter(prefix="/linux-config-generator", tags=["linux-config-generator"])


class LinuxGeneratorRequest(BaseModel):
    distro: Literal["debian", "ubuntu"] = "debian"
    modules: list[Literal["packages", "ssh", "bind9", "firewall"]] = Field(min_length=1)
    hostname: str = "nova-server"
    ssh_port: int = Field(default=22, ge=1, le=65535)
    dns_listen_address: str = "127.0.0.1"
    dns_forwarders: str = "1.1.1.1; 8.8.8.8"
    firewall_ssh: bool = True


class GeneratedFile(BaseModel):
    filename: str
    mime_type: str
    content: str


class GeneratorResponse(BaseModel):
    distro: str
    modules: list[str]
    files: list[GeneratedFile]
    warnings: list[str]


def _validate_hostname(hostname: str) -> bool:
    """Accept a DNS-style hostname with valid labels, excluding trailing dots."""
    if not hostname or len(hostname) > 253:
        return False
    labels = hostname.split(".")
    return all(
        1 <= len(label) <= 63
        and re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?", label) is not None
        for label in labels
    )


@router.post("/generate", response_model=GeneratorResponse)
def generate(payload: LinuxGeneratorRequest, current_user: User = Depends(get_current_user)) -> GeneratorResponse:
    if not _validate_hostname(payload.hostname):
        raise HTTPException(status_code=422, detail="Hostname tidak valid. Gunakan label alfanumerik dan tanda hubung di tengah label.")

    modules = list(dict.fromkeys(payload.modules))
    packages: list[str] = []
    native: list[tuple[str, str]] = [
        ("hostname.txt", payload.hostname + "\n"),
    ]
    warnings = [
        "Generator hanya membuat file; backend tidak mengeksekusi perintah pada host Linux.",
        "Hostname disimpan sebagai hostname.txt. Terapkan secara manual setelah meninjau README.",
        "Tinjau konfigurasi dan pastikan akses console tersedia sebelum mengubah SSH atau firewall.",
    ]

    if "packages" in modules:
        packages += ["curl", "ca-certificates", "vim"]

    if "ssh" in modules:
        packages.append("openssh-server")
        native.append((
            "60-nova.conf",
            f"# Generated by NOVA; review before installation\nPort {payload.ssh_port}\n"
            "PermitRootLogin prohibit-password\nPubkeyAuthentication yes\n"
            "PasswordAuthentication yes\nX11Forwarding no\n",
        ))
        warnings.append(
            "SSH mengizinkan autentikasi password pada template ini. Tinjau kebijakan autentikasi dan pastikan akses alternatif tersedia sebelum penerapan."
        )

    if "bind9" in modules:
        packages += ["bind9", "dnsutils"]
        try:
            # BIND's listen-on directive accepts IPv4 addresses only.
            listen = ipaddress.IPv4Address(payload.dns_listen_address)
            forwarders = [
                ipaddress.ip_address(item.strip())
                for item in payload.dns_forwarders.split(";")
                if item.strip()
            ]
            if not forwarders:
                raise ValueError("forwarder kosong")
        except ValueError as exc:
            raise HTTPException(status_code=422, detail="Alamat DNS listen/forwarder tidak valid.") from exc

        native.append((
            "named.conf.options",
            '// Generated by NOVA; review before installation\noptions {\n'
            '    directory "/var/cache/bind";\n'
            f"    listen-on {{ {listen}; }};\n"
            "    listen-on-v6 { none; };\n"
            "    recursion yes;\n"
            "    allow-query { localhost; };\n"
            "    allow-recursion { localhost; };\n"
            "    dnssec-validation auto;\n"
            "    forwarders { " + "; ".join(map(str, forwarders)) + "; };\n};\n",
        ))
        warnings.append(
            "BIND9 dibatasi untuk query dan recursion localhost. Jika DNS akan melayani LAN, tentukan ACL dan alamat listen secara eksplisit sebelum penerapan."
        )

    if "firewall" in modules:
        packages.append("ufw")
        rules = [
            "# Commands for manual review; not executed automatically",
            "ufw default deny incoming",
            "ufw default allow outgoing",
        ]
        if payload.firewall_ssh and "ssh" in modules:
            rules.append(f"ufw allow {payload.ssh_port}/tcp")
        else:
            rules.append("# SSH port is not opened automatically; add an explicit allow rule if required.")
        native.append(("nova-rules.txt", "\n".join(rules) + "\n"))
        warnings.append("Aturan UFW hanya berupa teks. Jangan aktifkan firewall sebelum memastikan aturan akses yang diperlukan.")

    packages = list(dict.fromkeys(packages))
    package_text = ", ".join(packages) if packages else "Tidak ada paket yang dipilih."
    readme = (
        f"NOVA Linux Configuration Generator\n"
        f"Target distro: {payload.distro}\n"
        "Package manager: apt (Debian/Ubuntu)\n"
        f"Selected modules: {', '.join(modules)}\n"
        f"Required packages: {package_text}\n\n"
        "This bundle is preview-only. It does not install packages, replace system files, "
        "change the hostname, apply firewall rules, or restart services.\n"
        "Review all files before manual application. Keep console access available when changing SSH or firewall settings.\n\n"
        "Manual file mapping (only apply files generated for selected modules):\n"
        "- hostname.txt: read the requested hostname; apply with hostnamectl only after review.\n"
        + ("- 60-nova.conf: /etc/ssh/sshd_config.d/60-nova.conf\n" if "ssh" in modules else "")
        + ("- named.conf.options: review and merge with /etc/bind/named.conf.options; do not blindly overwrite.\n" if "bind9" in modules else "")
        + ("- nova-rules.txt: review and run UFW commands manually; the firewall is not enabled by this generator.\n" if "firewall" in modules else "")
    )

    # All generated names and heredoc delimiters are fixed constants. User values
    # are validated and written only as file content, never interpolated into shell syntax.
    bundle_files: list[tuple[str, str]] = [("README.txt", readme), *native]
    script = [
        "#!/usr/bin/env bash",
        "set -Eeuo pipefail",
        "# NOVA preview script: creates a local bundle only; no system files are changed.",
        'OUT_DIR="$(pwd)/nova-linux-config"',
        'mkdir -p "$OUT_DIR"',
    ]
    for name, body in bundle_files:
        script.extend([
            f"cat > \"$OUT_DIR/{name}\" <<'NOVA_EOF'",
            body.rstrip("\n"),
            "NOVA_EOF",
        ])
    script.append('echo "Preview bundle created at: $OUT_DIR"')

    files = [
        GeneratedFile(
            filename="nova-linux-setup.sh",
            mime_type="text/x-shellscript",
            content="\n".join(script) + "\n",
        ),
        GeneratedFile(filename="README.txt", mime_type="text/plain", content=readme),
        *[
            GeneratedFile(filename=name, mime_type="text/plain", content=body)
            for name, body in native
        ],
        GeneratedFile(
            filename="manifest.json",
            mime_type="application/json",
            content=json.dumps({
                "generator": "NOVA Linux Configuration Generator",
                "distro": payload.distro,
                "package_manager": "apt",
                "modules": modules,
                "packages": packages,
                "native_files": [name for name, _ in native],
                "apply_automatically": False,
            }, indent=2) + "\n",
        ),
    ]
    return GeneratorResponse(distro=payload.distro, modules=modules, files=files, warnings=warnings)
