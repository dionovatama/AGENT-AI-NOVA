"""Safe, offline MikroTik configuration file generator.

Generates previewable .rsc, .json and .txt artifacts only. This module never
connects to or applies configuration to a router.
"""
from __future__ import annotations

import ipaddress
import json
import re
from typing import Literal

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app.database.models import User
from app.security.dependencies import get_current_user

router = APIRouter(prefix="/mikrotik-config-generator", tags=["mikrotik-config-generator"])

_INTERFACE_RE = re.compile(r"^[A-Za-z0-9_.-]{1,32}$")
_MODULES = {"ip", "dhcp", "nat", "firewall"}


class GeneratorRequest(BaseModel):
    routeros_version: Literal["6", "7"] = "7"
    modules: list[Literal["ip", "dhcp", "nat", "firewall"]] = Field(min_length=1)
    lan_interface: str = Field(default="bridge-lan", min_length=1, max_length=32)
    wan_interface: str = Field(default="ether1", min_length=1, max_length=32)
    wan_interfaces: list[str] | None = Field(default=None, max_length=8)
    ip_cidr: str = Field(default="192.168.88.1/24", max_length=43)
    dhcp_pool_start: str = Field(default="192.168.88.10", max_length=15)
    dhcp_pool_end: str = Field(default="192.168.88.254", max_length=15)
    dns_servers: str = Field(default="1.1.1.1,8.8.8.8", max_length=100)


class GeneratedFile(BaseModel):
    filename: str
    mime_type: str
    content: str


class GeneratorResponse(BaseModel):
    routeros_version: str
    modules: list[str]
    files: list[GeneratedFile]
    warnings: list[str]


def _safe_interface(value: str, field_name: str) -> str:
    if not _INTERFACE_RE.fullmatch(value):
        raise HTTPException(status_code=422, detail=f"{field_name} hanya boleh berisi huruf, angka, titik, garis bawah, dan tanda hubung.")
    return value


def _validated_values(payload: GeneratorRequest) -> tuple[ipaddress.IPv4Interface, list[str]]:
    _safe_interface(payload.lan_interface, "lan_interface")
    wan_interfaces = payload.wan_interfaces or [payload.wan_interface]
    if not wan_interfaces:
        raise HTTPException(status_code=422, detail="Minimal satu interface WAN diperlukan untuk NAT.")
    for interface_name in wan_interfaces:
        _safe_interface(interface_name, "wan_interfaces")
    if len(set(wan_interfaces)) != len(wan_interfaces):
        raise HTTPException(status_code=422, detail="Interface WAN tidak boleh duplikat.")
    if "dhcp" in payload.modules and "ip" not in payload.modules:
        raise HTTPException(status_code=422, detail="Modul DHCP membutuhkan modul IP agar gateway LAN ikut dikonfigurasi.")
    if len(set(payload.modules)) != len(payload.modules):
        raise HTTPException(status_code=422, detail="Modul konfigurasi tidak boleh duplikat.")
    try:
        interface = ipaddress.ip_interface(payload.ip_cidr)
        if not isinstance(interface, ipaddress.IPv4Interface):
            raise ValueError("IPv4 required")
    except ValueError as exc:
        raise HTTPException(status_code=422, detail="ip_cidr harus berupa alamat IPv4/CIDR yang valid.") from exc

    dns: list[str] = []
    try:
        for item in payload.dns_servers.split(","):
            item = item.strip()
            if not item:
                continue
            parsed = ipaddress.ip_address(item)
            if not isinstance(parsed, ipaddress.IPv4Address):
                raise ValueError("IPv4 required")
            dns.append(str(parsed))
    except ValueError as exc:
        raise HTTPException(status_code=422, detail="dns_servers harus berupa daftar alamat IPv4 dipisahkan koma.") from exc
    if "dhcp" in payload.modules:
        try:
            pool_start = ipaddress.ip_address(payload.dhcp_pool_start)
            pool_end = ipaddress.ip_address(payload.dhcp_pool_end)
            if not isinstance(pool_start, ipaddress.IPv4Address) or not isinstance(pool_end, ipaddress.IPv4Address):
                raise ValueError("IPv4 required")
            if int(pool_start) > int(pool_end):
                raise ValueError("pool start after end")
            if pool_start not in interface.network or pool_end not in interface.network:
                raise ValueError("pool outside subnet")
            if interface.ip in (pool_start, pool_end):
                raise ValueError("pool includes gateway")
            if int(pool_start) <= int(interface.ip) <= int(pool_end):
                raise ValueError("pool overlaps gateway")
        except ValueError as exc:
            raise HTTPException(status_code=422, detail="Rentang DHCP harus IPv4, berurutan, berada dalam subnet IP, dan tidak mencakup gateway.") from exc
        if not dns:
            raise HTTPException(status_code=422, detail="Minimal satu DNS IPv4 diperlukan untuk modul DHCP.")
    return interface, dns


def _build_rsc(payload: GeneratorRequest, interface: ipaddress.IPv4Interface, dns: list[str], template_name: str) -> str:
    header = [
        "# Generated by NOVA MikroTik Configuration Generator",
        f"# Target: RouterOS v{payload.routeros_version}",
        f"# Template: {template_name}",
        "# REVIEW BEFORE IMPORT. This file is not applied automatically.",
        "# Confirm interface names and existing configuration before use.",
        "",
    ]
    commands: list[str] = []
    if "ip" in payload.modules:
        commands += [
            f"/ip address add address={interface} interface={payload.lan_interface} comment=\"NOVA generated LAN address\"",
            "",
        ]
    if "dhcp" in payload.modules:
        pool_name = "nova-dhcp-pool"
        server_name = "nova-dhcp"
        commands += [
            f"/ip pool add name={pool_name} ranges={payload.dhcp_pool_start}-{payload.dhcp_pool_end}",
            f"/ip dhcp-server network add address={interface.network} gateway={interface.ip} dns-server={','.join(dns)}",
            f"/ip dhcp-server add name={server_name} interface={payload.lan_interface} address-pool={pool_name} disabled=no",
            "",
        ]
    if "nat" in payload.modules:
        wan_interfaces = payload.wan_interfaces or [payload.wan_interface]
        commands += [
            f"/ip firewall nat add chain=srcnat out-interface={wan_name} action=masquerade comment=\"NOVA generated NAT {wan_name}\""
            for wan_name in wan_interfaces
        ]
        commands += [""]
    if "firewall" in payload.modules:
        # Conservative additions only; no blanket input drop that could lock out management.
        commands += [
            "/ip firewall filter add chain=input connection-state=established,related action=accept comment=\"NOVA: accept established input\"",
            "/ip firewall filter add chain=input connection-state=invalid action=drop comment=\"NOVA: drop invalid input\"",
            "/ip firewall filter add chain=input protocol=icmp action=accept comment=\"NOVA: allow ICMP input\"",
            "/ip firewall filter add chain=forward connection-state=established,related action=accept comment=\"NOVA: accept established forward\"",
            "/ip firewall filter add chain=forward connection-state=invalid action=drop comment=\"NOVA: drop invalid forward\"",
            "",
        ]
    return "\n".join(header + commands).rstrip() + "\n"


def _build_rsc_v6(payload: GeneratorRequest, interface: ipaddress.IPv4Interface, dns: list[str]) -> str:
    """RouterOS v6 template entry point."""
    return _build_rsc(payload, interface, dns, "routeros-v6")


def _build_rsc_v7(payload: GeneratorRequest, interface: ipaddress.IPv4Interface, dns: list[str]) -> str:
    """RouterOS v7 template entry point."""
    return _build_rsc(payload, interface, dns, "routeros-v7")


@router.post("/generate", response_model=GeneratorResponse)
def generate_configuration(
    payload: GeneratorRequest,
    current_user: User = Depends(get_current_user),
) -> GeneratorResponse:
    """Generate files only; no device connection, execution, or persistent storage."""
    interface, dns = _validated_values(payload)
    modules = list(dict.fromkeys(payload.modules))
    # Preserve a version-specific template entry point, even where safe commands
    # are intentionally identical between RouterOS v6 and v7.
    if payload.routeros_version == "6":
        rsc = _build_rsc_v6(payload, interface, dns)
    else:
        rsc = _build_rsc_v7(payload, interface, dns)

    data = {
        "generator": "NOVA MikroTik Configuration Generator",
        "routeros_version": payload.routeros_version,
        "modules": modules,
        "parameters": {
            "lan_interface": payload.lan_interface,
            "wan_interface": payload.wan_interface,
            "wan_interfaces": payload.wan_interfaces or [payload.wan_interface],
            "ip_cidr": str(interface),
            "network": str(interface.network),
            "dhcp_pool_start": payload.dhcp_pool_start if "dhcp" in modules else None,
            "dhcp_pool_end": payload.dhcp_pool_end if "dhcp" in modules else None,
            "dns_servers": dns,
        },
        "apply_automatically": False,
    }
    docs = [
        "NOVA — MikroTik Configuration Preview",
        f"Target RouterOS: v{payload.routeros_version}",
        f"Modules: {', '.join(modules)}",
        "",
        "Files are generated only. No router has been contacted or modified.",
        "Before import: back up the router, verify interface names, inspect duplicate rules/addresses,",
        "and test during a maintenance window. RouterOS v6/v7 command behavior can vary by device.",
        "",
        "Parameters:",
        json.dumps(data["parameters"], indent=2, ensure_ascii=False),
        "",
        "RouterOS script:",
        rsc,
    ]
    warnings = [
        "Generator hanya membuat file; tidak menguji sintaks pada router dan tidak menerapkan perubahan.",
        "Pastikan interface sudah ada dan periksa konfigurasi yang sudah berjalan agar tidak membuat alamat atau rule duplikat.",
        "Rule firewall sengaja tidak menambahkan blanket drop untuk mengurangi risiko lockout; ini bukan hardening firewall lengkap.",
    ]
    files = [
        GeneratedFile(filename=f"nova-mikrotik-routeros-v{payload.routeros_version}.rsc", mime_type="text/plain", content=rsc),
        GeneratedFile(filename=f"nova-mikrotik-routeros-v{payload.routeros_version}.json", mime_type="application/json", content=json.dumps(data, indent=2, ensure_ascii=False) + "\n"),
        GeneratedFile(filename=f"nova-mikrotik-routeros-v{payload.routeros_version}.txt", mime_type="text/plain", content="\n".join(docs) + "\n"),
    ]
    return GeneratorResponse(routeros_version=payload.routeros_version, modules=modules, files=files, warnings=warnings)
