"""Offline Linux configuration generator for Debian and Ubuntu.

Creates reviewable shell scripts and/or native configuration files. Nothing is
executed on the NOVA backend and no remote host is contacted.
"""
from __future__ import annotations

import re
import shlex
from typing import Literal

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app.database.models import User
from app.security.dependencies import get_current_user

router = APIRouter(prefix="/linux-config-generator", tags=["linux-config-generator"])

_SAFE_HOST = re.compile(r"^[A-Za-z0-9.-]{1,253}$")
_SAFE_IP = re.compile(r"^[0-9a-fA-F:.]{2,45}$")


class LinuxGeneratorRequest(BaseModel):
    distro: Literal["debian", "ubuntu"] = "debian"
    output_mode: Literal["script", "config", "both"] = "both"
    modules: list[Literal["ssh", "ufw"]] = Field(min_length=1, max_length=2)
    ssh_port: int = Field(default=22, ge=1, le=65535)
    ufw_allow_ssh: bool = True


class GeneratedFile(BaseModel):
    filename: str
    mime_type: str
    content: str


class LinuxGeneratorResponse(BaseModel):
    distro: str
    output_mode: str
    modules: list[str]
    files: list[GeneratedFile]
    warnings: list[str]


def _native_files(payload: LinuxGeneratorRequest) -> list[GeneratedFile]:
    files: list[GeneratedFile] = []
    if "ssh" in payload.modules:
        files.append(GeneratedFile(
            filename="60-nova-hardening.conf",
            mime_type="text/plain",
            content=(
                "# NOVA-generated SSH drop-in. Review before installing.\n"
                "PermitRootLogin no\n"
                "MaxAuthTries 4\n"
                "X11Forwarding no\n"
                "AllowTcpForwarding no\n"
            ),
        ))
    if "ufw" in payload.modules:
        ports = ["53"]
        if payload.ufw_allow_ssh:
            ports.append(str(payload.ssh_port))
        files.append(GeneratedFile(
            filename="ufw-rules.sh",
            mime_type="text/x-shellscript",
            content="#!/usr/bin/env bash\nset -euo pipefail\n# Review source/interface restrictions before use. This does not enable UFW.\n"
            + "".join(f"ufw allow {shlex.quote(port + '/tcp')}\nufw allow {shlex.quote(port + '/udp')}\n" for port in ports),
        ))
    return files


def _script(payload: LinuxGeneratorRequest, native_files: list[GeneratedFile]) -> str:
    packages = []
    if "ssh" in payload.modules:
        packages.append("openssh-server")
    if "ufw" in payload.modules:
        packages.append("ufw")
    lines = [
        "#!/usr/bin/env bash",
        "set -Eeuo pipefail",
        "# Generated by NOVA Linux Configuration Generator.",
        "# Review this script before running. It makes changes to this host.",
        "if [[ ${EUID} -ne 0 ]]; then echo 'Run with sudo: sudo bash this-script.sh' >&2; exit 1; fi",
        "export DEBIAN_FRONTEND=noninteractive",
        "apt-get update",
        "apt-get install -y " + " ".join(shlex.quote(p) for p in packages),
        "",
        "backup_file() {",
        "  local target=\"$1\"",
        "  if [[ -f \"$target\" ]]; then cp -a \"$target\" \"${target}.nova-backup.$(date +%Y%m%d%H%M%S)\"; fi",
        "}",
        "",
    ]
    for file in native_files:
        if file.filename == "ufw-rules.sh":
            lines += [
                "# Firewall rules are printed for review and are not automatically enabled.",
                "echo 'UFW installed. Review and apply firewall rules manually; UFW is not enabled by this script.'",
                "",
            ]
            continue
        if file.filename == "60-nova-hardening.conf":
            target = "/etc/ssh/sshd_config.d/60-nova-hardening.conf"
            service = "ssh"
        else:
            continue
        lines += [
            f"target={shlex.quote(target)}",
            "install -d -m 0755 \"$(dirname \"$target\")\"",
            "backup_file \"$target\"",
            "tmp=\"$(mktemp)\"",
            "cat > \"$tmp\" <<'NOVA_CONFIG_EOF'",
            file.content.rstrip(),
            "NOVA_CONFIG_EOF",
            "install -o root -g root -m 0644 \"$tmp\" \"$target\"",
            "rm -f \"$tmp\"",
        ]
        if service == "ssh":
            lines += [
                "if sshd -t; then systemctl reload ssh || systemctl restart ssh; else echo 'SSH config invalid; restore the backup before continuing.' >&2; exit 1; fi",
            ]
        lines.append("")
    lines += ["echo 'NOVA configuration script completed. Verify each service status.'", ""]
    return "\n".join(lines)


@router.post("/generate", response_model=LinuxGeneratorResponse)
def generate_linux_configuration(
    payload: LinuxGeneratorRequest,
    current_user: User = Depends(get_current_user),
) -> LinuxGeneratorResponse:
    """Generate files only; never executes commands or connects to a Linux host."""
    if len(set(payload.modules)) != len(payload.modules):
        raise HTTPException(status_code=422, detail="Modul konfigurasi tidak boleh duplikat.")
    native = _native_files(payload)
    files: list[GeneratedFile] = []
    if payload.output_mode in {"config", "both"}:
        files.extend(native)
    if payload.output_mode in {"script", "both"}:
        files.insert(0, GeneratedFile(
            filename=f"nova-{payload.distro}-setup.sh",
            mime_type="text/x-shellscript",
            content=_script(payload, native),
        ))
    warnings = [
        "Periksa isi file sebelum digunakan; generator tidak menguji konfigurasi pada host target.",
        "SSH: PermitRootLogin no dapat mengubah cara administrasi. Pastikan akun sudo non-root sudah bisa login sebelum menerapkan.",
    ]
    if "ufw" in payload.modules:
        warnings.append("Aturan UFW hanya dibuat sebagai file review; script tidak mengaktifkan firewall untuk menghindari risiko memutus koneksi.")
    return LinuxGeneratorResponse(
        distro=payload.distro,
        output_mode=payload.output_mode,
        modules=list(payload.modules),
        files=files,
        warnings=warnings,
    )
